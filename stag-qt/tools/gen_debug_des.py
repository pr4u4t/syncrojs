#!/usr/bin/env python3
"""Descriptions and colours of the DM words on frm_debug_des, by running fil_des and col_lab of the VB source."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VB = ROOT.parent / "stag"
OUT = ROOT / "src/logic/debugdes.inc"


def source(name):
    return (VB / name).read_text(encoding="cp1252", errors="replace").replace("\r\n", "\n")


def body(text, header):
    match = re.search(rf"^Sub {header}\b.*?^End Sub", text, re.M | re.S)
    return [line.split("'")[0].strip() if not line.strip().startswith("add_des") else line.strip() for line in match.group(0).split("\n")[1:-1]]


def constants():
    values = {"vbWhite": 0xFFFFFF}
    for name, raw in re.findall(r"^Public Const (\w+) = &H([0-9A-Fa-f]+)&?", source("Var_stag.bas"), re.M):
        values[name] = int(raw, 16)
    return values


def run(lines, env, emit):
    pc = 0
    loops = []
    while pc < len(lines):
        line = lines[pc]
        pc += 1
        if match := re.fullmatch(r"(\w+) = (.+)", line):
            env[match[1]] = eval(match[2], {}, env)
        elif match := re.fullmatch(r"For (\w+) = (.+) To (.+)", line):
            env[match[1]] = eval(match[2], {}, env)
            end = eval(match[3], {}, env)
            if env[match[1]] <= end:
                loops.append((match[1], end, pc))
            else:
                depth = 1
                while depth:
                    depth += lines[pc].startswith("For ") - lines[pc].startswith("Next ")
                    pc += 1
        elif line.startswith("Next "):
            name, end, start = loops[-1]
            env[name] += 1
            if env[name] <= end:
                pc = start
            else:
                loops.pop()
        elif line:
            emit(line, env)


def descriptions(text):
    result = {}

    def emit(line, env):
        match = re.fullmatch(r'add_des ("(?:[^"]|"")*"(?: *& *\w+(?: *\+ *\d+)?(?: *& *"(?:[^"]|"")*")*)*), CStr\((\w+)\)', line)
        if not match:
            if line.startswith(("Set ", "Dim ")):
                return
            sys.exit(f"fil_des: cannot read {line!r}")
        expression = re.sub(r"\s*&\s*", "+", match[1]).replace('""', '\\"')
        expression = re.sub(r"\b([im])\b", r"str(\1)", expression)
        result[env[match[2]]] = eval(expression, {}, env)

    run(body(text, "fil_des"), {}, emit)
    return result


def colours(text, values):
    lines = body(text, "col_lab")
    cases = {}
    current = None
    for line in lines:
        if match := re.fullmatch(r"Case (\d+)", line):
            current = int(match[1])
            cases[current] = []
        elif current and line != "End Select":
            cases[current].append(line)
    result = {}
    for block, code in cases.items():
        row = {}

        def emit(line, env, row=row):
            match = re.fullmatch(r"lab_dm\((\w+)\)\.BackColor = (\w+)", line)
            if not match:
                sys.exit(f"col_lab: cannot read {line!r}")
            index = env["i"] if match[1] == "i" else int(match[1])
            row[index] = values[match[2]]

        run(code, {"i": 0}, emit)
        result[block] = row
    return result


def main():
    text = source("frm_debug_des.frm")
    out = ["// Generated by tools/gen_debug_des.py from frm_debug_des.frm. Do not edit.", ""]
    out.append("static const struct { int dm; const char *text; } DEBUG_DES[] = {")
    for dm, description in sorted(descriptions(text).items()):
        escaped = description.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    {{{dm}, "{escaped}"}},')
    out += ["};", "", "static const struct { int block; int index; quint32 color; } DEBUG_COLORS[] = {"]
    for block, row in sorted(colours(text, constants()).items()):
        out += [f"    {{{block}, {index}, 0x{color:06X}}}," for index, color in sorted(row.items())]
    out += ["};", ""]
    content = "\n".join(out)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == content else "debugdes.inc is out of date")
    OUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
