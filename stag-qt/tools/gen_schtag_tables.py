#!/usr/bin/env python3
"""Field tables of set_par_sch_tag1/2/4/5 and the ini writers, read from the VB source, so the places
where VB mixes par_mac and par_mac_ute or skips a field stay as they are."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VB = ROOT.parent / "stag"
OUT = ROOT / "src/logic/schtagtables.inc"
PAGES = (1, 2, 4, 5)


def text(name):
    return (VB / name).read_text(encoding="cp1252", errors="replace").replace("\r\n", "\n")


def body(source, header):
    match = re.search(rf"^(?:Private )?Sub {header}\b.*?^End Sub", source, re.M | re.S)
    if not match:
        sys.exit(f"missing {header}")
    return [line.split("'")[0].strip() for line in match.group(0).split("\n")]


def member(name):
    return name.replace("1°", "1o").replace("2°", "2o").replace("1\xb0", "1o").replace("2\xb0", "2o")


def tab_order(source):
    found = re.findall(r"Begin VB\.TextBox (\w*?_att)\b(.*?)^\s*End\b", source, re.M | re.S)
    orders = []
    for name, props in found:
        match = re.search(r"TabIndex\s*=\s*(\d+)", props)
        if match:
            orders.append((int(match.group(1)), name))
    return [name for _, name in sorted(orders)]


def page_tables(page):
    source = text(f"set_par_sch_tag{page}.frm").replace("\xb0", "o")
    tables = {}
    for kind, sub in (("att", "fil_par_sch_tag_liv"), ("def", "fil_par_sch_tag_def_liv")):
        rows = []
        for line in body(source, sub):
            match = re.fullmatch(r"(\w+) = Trim\((par_mac(?:_ute)?)\.(sch_tag(?:_def)?)\.sch_tag_liv\(liv\)\.(\w+)\)", line)
            if match:
                rows.append((match.group(1), member(match.group(4)), match.group(2) == "par_mac_ute", match.group(3) == "sch_tag_def"))
            elif line.startswith("txt_"):
                sys.exit(f"page {page}: cannot read {line!r}")
        tables["fil_" + kind] = rows
    for kind, sub, tree in (("att", "scr_par_att_ute_liv", "sch_tag"), ("def", "scr_par_def_ute_liv", "sch_tag_def")):
        rows = []
        for line in body(source, sub):
            match = re.fullmatch(rf"par_mac_ute\.{tree}\.sch_tag_liv\(liv\)\.(\w+) = (\w+)", line)
            if match:
                rows.append((match.group(2), member(match.group(1))))
            elif line.startswith("par_mac_ute") and "sch_tag_liv" in line:
                sys.exit(f"page {page}: cannot read {line!r}")
        tables["scr_" + kind] = rows
    tables["copy"] = []
    for line in body(source, "att_in_def"):
        match = re.fullmatch(r"(txt_\w+_def) = (txt_\w+_att)", line)
        if match:
            tables["copy"].append((match.group(2), match.group(1)))
    tables["tab"] = tab_order(source)
    return tables


def def_in_att():
    source = text("sch_tag_bas.bas").replace("\xb0", "o")
    result = {}
    current = None
    for line in body(source, "def_in_att"):
        case = re.fullmatch(r'Case "set_par_sch_tag(\d)"', line)
        if case:
            current = int(case.group(1))
            result[current] = []
        match = re.fullmatch(r"par_mac_ute\.sch_tag\.sch_tag_liv\(Livello\)\.(\w+) = par_mac\.sch_tag_def\.sch_tag_liv\(Livello\)\.\w+", line)
        if match and current:
            result[current].append(member(match.group(1)))
    return result


def ini_keys(sub):
    rows = []
    for line in body(text("ini_bas.bas").replace("\xb0", "o"), sub):
        match = re.fullmatch(r'setFileINIString str1, "(\w+)", Trim\$\(par_mac\.\w+\.sch_tag_liv\(liv\)\.(\w+)\), app\.EXEName', line)
        if match:
            rows.append((match.group(1), member(match.group(2))))
    return rows


def main():
    copies = def_in_att()
    out = ["// Generated by tools/gen_schtag_tables.py from the VB source. Do not edit.", ""]
    for page in PAGES:
        tables = page_tables(page)
        for kind in ("att", "def"):
            out.append(f"static const SchTagFil FIL_{kind.upper()}_{page}[] = {{")
            out += [f'    {{"{c}", &TipSchTagLiv::{f}, {"true" if u else "false"}, {"true" if d else "false"}}},' for c, f, u, d in tables["fil_" + kind]]
            out += ["};"]
            out.append(f"static const SchTagScr SCR_{kind.upper()}_{page}[] = {{")
            out += [f'    {{"{c}", &TipSchTagLiv::{f}}},' for c, f in tables["scr_" + kind]]
            out += ["};"]
        out.append(f"static const SchTagCopy COPY_{page}[] = {{")
        out += [f'    {{"{a}", "{d}"}},' for a, d in tables["copy"]]
        out += ["};"]
        out.append(f"static const char *const TAB_{page}[] = {{")
        out += [f'    "{name}",' for name in tables["tab"]]
        out += ["};"]
        out.append(f"static FixStr TipSchTagLiv::*const DEF_IN_ATT_{page}[] = {{")
        out += [f"    &TipSchTagLiv::{f}," for f in copies[page]]
        out += ["};", ""]
    for name, sub in (("INI_ATT", "scr_par_sch_tag_att_liv_ini"), ("INI_DEF", "scr_par_sch_tag_def_liv_ini")):
        out.append(f"static const SchTagIni {name}[] = {{")
        out += [f'    {{"{k}", &TipSchTagLiv::{f}}},' for k, f in ini_keys(sub)]
        out += ["};", ""]
    content = "\n".join(out)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == content else "schtagtables.inc is out of date")
    OUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
